// Exports the demo roster to (1) a CSV that opens in Excel and (2) the frontend's offline demo roster.
// Usage: npm run export:credentials -- [path/to/Demo Login Credentials.csv]
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { roster, loginPanelAccounts, EMAIL_DOMAIN } from '../src/repositories/roster.js';

const csvPath = resolve(process.argv[2] || 'Demo Login Credentials.csv');
const escape = (value: string) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);
const label = (role: string) => role.charAt(0).toUpperCase() + role.slice(1);

const rows = [
  ['Username', 'Email', 'Full Name', 'Role', 'Roll No', 'Demo password', 'Shown on sign-in page'],
  ...roster.map(person => [
    person.username, person.email, person.fullName, label(person.role), person.rollNo || '', person.password,
    loginPanelAccounts.some(item => item.id === person.id) ? 'Yes' : 'No'
  ])
];
writeFileSync(csvPath, '﻿' + rows.map(row => row.map(escape).join(',')).join('\r\n') + '\r\n', 'utf8');

const frontendPath = resolve(import.meta.dirname, '../../Frontend/src/lib/demoRoster.ts');
const compact = roster.map(({ id, fullName, username, role, rollNo, password }) => ({ id, fullName, username, role, rollNo, password }));
writeFileSync(frontendPath, `// GENERATED by Backend/scripts/export-credentials.ts from Backend/src/repositories/roster.ts. Do not edit by hand.
// Demo-only credentials for the offline demo fallback and the sign-in page panel.
export const EMAIL_DOMAIN = '${EMAIL_DOMAIN}';

export interface DemoRosterEntry {
  id: string;
  fullName: string;
  username: string;
  role: 'admin' | 'teacher' | 'student';
  rollNo: string | null;
  password: string;
}

export const demoRoster: DemoRosterEntry[] = ${JSON.stringify(compact, null, 2)};

/** Usernames shown on the sign-in page: 1 admin, every teacher, 5 students. */
export const loginPanelUsernames: string[] = ${JSON.stringify(loginPanelAccounts.map(person => person.username), null, 2)};
`, 'utf8');

console.log(`Wrote ${roster.length} accounts to ${csvPath}`);
console.log(`Wrote frontend roster to ${frontendPath}`);
